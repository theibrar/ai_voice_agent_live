export function translate(keyOrText: string, lang: string = "en"): string {
  if (!keyOrText) return "";
  if (lang === "en") {
    // Return original key or English translation if available
    if (TRANSLATIONS["en"] && TRANSLATIONS["en"][keyOrText]) {
      return TRANSLATIONS["en"][keyOrText];
    }
    return keyOrText;
  }

  // 1. Direct translation key match in target language
  if (TRANSLATIONS[lang] && TRANSLATIONS[lang][keyOrText]) {
    return TRANSLATIONS[lang][keyOrText];
  }

  // 2. Normalized string lookup via STRING_KEY_MAP
  const normalized = keyOrText.toLowerCase().trim().replace(/^[+•-]\s*/, "");
  const mappedKey = STRING_KEY_MAP[normalized] || STRING_KEY_MAP[keyOrText.toLowerCase().trim()];
  if (mappedKey) {
    if (TRANSLATIONS[lang] && TRANSLATIONS[lang][mappedKey]) {
      const isPlus = keyOrText.trim().startsWith("+");
      return isPlus ? `+ ${TRANSLATIONS[lang][mappedKey]}` : TRANSLATIONS[lang][mappedKey];
    }
    // Fallback translation in German, Spanish, French, etc.
    if (TRANSLATIONS["de"] && TRANSLATIONS["de"][mappedKey] && lang === "de") {
      return TRANSLATIONS["de"][mappedKey];
    }
    if (TRANSLATIONS["es"] && TRANSLATIONS["es"][mappedKey] && lang === "es") {
      return TRANSLATIONS["es"][mappedKey];
    }
  }

  // 3. Substring / Word-level fallback matching for composite labels
  if (normalized.includes("contact") && normalized.includes("lead")) {
    if (TRANSLATIONS[lang]?.contacts_database) return TRANSLATIONS[lang].contacts_database;
  }
  if (normalized.includes("export") && normalized.includes("csv")) {
    if (TRANSLATIONS[lang]?.export_csv) return TRANSLATIONS[lang].export_csv;
  }
  if (normalized.includes("add") && normalized.includes("lead")) {
    if (TRANSLATIONS[lang]?.add_lead) return `+ ${TRANSLATIONS[lang].add_lead}`;
  }

  // 4. Default return original text if no translation rule exists
  return keyOrText;
}
