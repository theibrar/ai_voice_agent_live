export const LANGUAGE_STORAGE_KEY = "apex_preferred_language";

export function getStoredLanguage(): string {
  if (typeof window === "undefined") return "en";
  try {
    return localStorage.getItem(LANGUAGE_STORAGE_KEY) || "en";
  } catch {
    return "en";
  }
}

export function setStoredLanguage(code: string): void {
  if (typeof window === "undefined") return;
  try {
    localStorage.setItem(LANGUAGE_STORAGE_KEY, code);
    const lang = BASIC_LANGUAGES.find((l) => l.code === code);
    if (lang && document.documentElement) {
      document.documentElement.setAttribute("lang", code);
      document.documentElement.setAttribute("dir", lang.dir || "ltr");
    }
    window.dispatchEvent(new CustomEvent("apex-language-change", { detail: code }));
  } catch (e) {
    console.error("Failed to save preferred language", e);
  }
}

